"""What goes into someone else's repo: a README-sized GIF of the best scene,
the badge, the report, and the markdown snippet that ties them together.

`export_assets()` collects it all into a `.ttywood/` directory (the Action
commits that directory to the project and opens a PR); `snippet()` is the
block a maintainer pastes into the README once. Paths in the snippet are
relative to the repo root so it renders on GitHub with no hosting."""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

from . import PROJECT_URL
from .check import Report, load_report

GIF_WIDTH = 900
GIF_FPS = 12
GIF_MAX_SECONDS = 30
GIF_MIN_SECONDS = 18   # a scene can be 4 s once waits are fast-forwarded; keep rolling into the next
ASSET_DIR = ".ttywood"


def readme_gif(episode_dir: Path, scene_id: str | None = None,
               width: int = GIF_WIDTH, max_seconds: float = GIF_MAX_SECONDS) -> Path:
    """`readme.gif`: the Short's scene (the tool doing its trick, never the
    install) cut from the rendered terminal body, README sized. Needs a
    rendered episode (demo_body.mp4 + render_meta.json with body_timeline)."""
    episode_dir = episode_dir.resolve()
    meta = json.loads((episode_dir / "render_meta.json").read_text())
    scenes = meta.get("body_timeline") or []
    if not scenes:
        raise RuntimeError("no body_timeline: render the cinematic cut first")
    from .screenplay import load_screenplay
    from .shorts import pick_scene
    wanted = scene_id
    if not wanted and (episode_dir / "screenplay.yaml").exists():
        wanted = load_screenplay(episode_dir / "screenplay.yaml").meta.short_scene
    sc = pick_scene(scenes, wanted)
    start = sc["start"]
    body_end = max(s["end"] for s in scenes)
    # the picked scene, then the scenes after it until the GIF is long enough
    # to be worth looping (never past the body, never past max_seconds)
    end = min(max(sc["end"], start + GIF_MIN_SECONDS), body_end, start + max_seconds)
    length = end - start
    out = episode_dir / "readme.gif"
    vf = (f"fps={GIF_FPS},scale={width}:-1:flags=lanczos,"
          "split[a][b];[a]palettegen=max_colors=128:stats_mode=diff[p];"
          "[b][p]paletteuse=dither=bayer:bayer_scale=4:diff_mode=rectangle")
    subprocess.run(["ffmpeg", "-nostdin", "-y", "-v", "error", "-ss", f"{start:.2f}", "-t", f"{length:.2f}",
                    "-i", str(episode_dir / "demo_body.mp4"), "-vf", vf, "-loop", "0", str(out)],
                   check=True)
    return out


def video_url(episode_dir: Path) -> str:
    pub = episode_dir / "published.json"
    if not pub.exists():
        return ""
    data = json.loads(pub.read_text())
    entry = data.get("episode") if "episode" in data else data  # old single-entry format
    return (entry or {}).get("url", "")


def snippet(r: Report, episode_dir: Path, asset_dir: str = ASSET_DIR) -> str:
    """Markdown for the project's README. Everything is a relative path into
    asset_dir, so it works from the PR the Action opens; the YouTube link is
    added when the episode was published."""
    url = video_url(episode_dir)
    lines = [f"[![ttywood clean-room check]({asset_dir}/badge.svg)]({asset_dir}/report.md)"]
    if (episode_dir / "readme.gif").exists():
        gif = f"![{r.tool or r.repo} demo]({asset_dir}/readme.gif)"
        lines += ["", f"[{gif}]({url})" if url else gif]
        if url:
            lines += ["", f"[Watch the full episode]({url}): installed from a clean machine, "
                          "the docs followed as written, what worked and what did not."]
    lines += ["", f"<sub>Checked by [ttywood]({PROJECT_URL}) on {r.checked_at[:10]} "
                  f"at commit `{r.ref[:7]}`: {r.summary} "
                  f"[Full report]({asset_dir}/report.md).</sub>"]
    return "\n".join(lines) + "\n"


def export_assets(episode_dir: Path, dest: Path, with_gif: bool = True) -> list[Path]:
    """Copy badge, report, GIF and the snippet into dest (the target repo's
    .ttywood/). Returns the files written."""
    episode_dir = episode_dir.resolve()
    dest = dest.resolve()
    dest.mkdir(parents=True, exist_ok=True)
    r = load_report(episode_dir / "report.json")
    from .badge import write_badge
    write_badge(episode_dir, r)
    if with_gif and not (episode_dir / "readme.gif").exists() and (episode_dir / "demo_body.mp4").exists():
        readme_gif(episode_dir)
    written = []
    for name in ("badge.svg", "badge.json", "report.json", "report.md", "readme.gif"):
        src = episode_dir / name
        if src.exists():
            shutil.copy(src, dest / name)
            written.append(dest / name)
    (dest / "README-snippet.md").write_text(snippet(r, episode_dir))
    written.append(dest / "README-snippet.md")
    (dest / "README.md").write_text(
        "# .ttywood\n\nGenerated by [ttywood](" + PROJECT_URL + "): a clean-room check of "
        "this project (a fresh Ubuntu container, the docs followed as written) and, when an "
        "episode was recorded, a README GIF of the tool in use. `report.md` has the findings, "
        "`badge.svg` the verdict, `README-snippet.md` the block to paste into the main README. "
        "Regenerated by the ttywood Action on every release; do not edit by hand.\n")
    written.append(dest / "README.md")
    return written
