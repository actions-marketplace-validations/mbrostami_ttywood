"""<episodes>/INDEX.md: one row per episode with what it is, whether it passed QA
and whether it is on YouTube. Rewritten after every run and every publish,
so the file in git always says which episodes are live."""

from __future__ import annotations

import datetime as dt
import json
import subprocess
from pathlib import Path


def _duration(video: Path) -> str:
    if not video.exists():
        return ""
    p = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                        "-of", "csv=p=0", str(video)], capture_output=True, text=True)
    try:
        s = int(float(p.stdout.strip()))
        return f"{s // 60}m{s % 60:02d}s"
    except ValueError:
        return ""


def _qa(ep: Path) -> str:
    q = ep / "qa.md"
    if not q.exists():
        return ""
    text = q.read_text()
    return "PASS" if "Verdict: PASS" in text else ("FAIL" if "Verdict: FAIL" in text else "")


def _check(ep: Path) -> str:
    """'pass 2026-08-28 (3)' from report.json: verdict, date, findings count."""
    r = ep / "report.json"
    if not r.exists():
        return ""
    try:
        d = json.loads(r.read_text())
        return f"{d.get('verdict', '')} {d.get('checked_at', '')[:10]} ({len(d.get('findings', []))})"
    except (OSError, ValueError):
        return ""


def episode_row(ep: Path) -> dict:
    c = json.loads((ep / "candidate.json").read_text()) if (ep / "candidate.json").exists() else {}
    pub = json.loads((ep / "published.json").read_text()) if (ep / "published.json").exists() else {}
    if "id" in pub:  # old single-entry format
        pub = {("short" if pub.get("short") else "episode"): pub}
    e, s = pub.get("episode", {}), pub.get("short", {})
    if e:
        status = "published" if not s else "published + short"
    elif (ep / "final.mp4").exists():
        status = "ready" if _qa(ep) == "PASS" else ("qa failed" if _qa(ep) == "FAIL" else "rendered")
    elif (ep / "screenplay.yaml").exists():
        status = "rehearsed"
    elif (ep / "report.json").exists():
        status = "checked"
    else:
        status = "picked"
    return {
        "episode": ep.name, "repo": c.get("repo", ""), "structure": c.get("structure", ""),
        "duration": _duration(ep / "final.mp4"), "qa": _qa(ep), "status": status,
        "check": _check(ep),
        "episode_url": e.get("url", ""), "short_url": s.get("url", ""),
        "published_at": e.get("published_at", ""), "privacy": e.get("privacy", ""),
    }


# what an agent driving ttywood usually wants to pick up afterwards
ARTIFACTS = ("candidate.json", "notes.md", "screenplay.yaml", "demo.cast", "final.mp4",
             "short.mp4", "thumbnail.png", "narration.md", "narration.srt", "youtube.md",
             "qa.md", "readme.gif", "report.md", "report.json", "badge.svg")


def episode_info(ep: Path) -> dict:
    """One episode's row plus the paths of the artifacts that exist."""
    if not ep.is_dir():
        raise FileNotFoundError(f"no episode at {ep}")
    row = episode_row(ep)
    row["dir"] = str(ep)
    row["files"] = {name: str(ep / name) for name in ARTIFACTS if (ep / name).exists()}
    return row


def episode_rows(root: Path) -> list[dict]:
    rows = [episode_row(cand.parent) for cand in sorted(root.glob("*/candidate.json"))]
    order = {"published + short": 0, "published": 1, "ready": 2, "qa failed": 3,
             "rendered": 4, "rehearsed": 5, "checked": 6, "picked": 7}
    return sorted(rows, key=lambda r: (order.get(r["status"], 9), r["episode"]))


def write_index(root: Path) -> Path:
    rows = episode_rows(root)
    live = [r for r in rows if r["status"].startswith("published")]
    ready = [r for r in rows if r["status"] == "ready"]
    lines = ["# Episodes", "",
             f"Updated {dt.datetime.now().strftime('%Y-%m-%d %H:%M')} local. "
             f"{len(live)} published, {len(ready)} ready to publish, {len(rows)} total. "
             "Regenerated by the pipeline (`ttywood status` rewrites it); do not edit by hand.", "",
             "| episode | repo | status | QA | check | length | episode | short | privacy |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        ep_link = f"[{r['episode_url'].rsplit('/', 1)[-1]}]({r['episode_url']})" if r["episode_url"] else ""
        sh_link = f"[{r['short_url'].rsplit('/', 1)[-1]}]({r['short_url']})" if r["short_url"] else ""
        lines.append(f"| {r['episode']} | {r['repo']} | {r['status']} | {r['qa']} | {r['check']} "
                     f"| {r['duration']} | {ep_link} | {sh_link} | {r['privacy']} |")
    lines += ["", "Status: `published` on YouTube (private until flipped), `ready` = QA PASS and "
              "not uploaded, `qa failed` = needs a fix, `rendered`/`rehearsed`/`picked` = "
              "stopped earlier in the pipeline, `checked` = clean-room check only (no video). "
              "Check column: verdict, date, number of findings from `report.json`.", ""]
    out = root / "INDEX.md"
    out.write_text("\n".join(lines))
    return out
